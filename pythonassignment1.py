def file_handling():
    with open("student_records.txt", "w") as f:
        f.write("ID,Name,Marks\n101,Arjun,85\n102,Meera,92\n103,Ravi,76\n104,Anita,89\n")
    print("Records written to file.")

    with open("student_records.txt", "r") as f:
        records = f.readlines()
    print("\nStored Records:")
    for r in records:
        print(r.strip())

    total_students, total_marks, highest_marks = 0, 0, -1
    top_student = ""
    for rec in records[1:]:
        _, name, marks = rec.strip().split(",")
        marks = int(marks)
        total_students += 1
        total_marks += marks
        if marks > highest_marks:
            highest_marks, top_student = marks, name
    print("\nReport:")
    print("Total Students:", total_students)
    print("Average Marks:", total_marks/total_students)
    print("Top Student:", top_student, "with", highest_marks)

# ------------------ Q7: Directory Scanning with Graph ------------------
class MissingFileOrFolderError(Exception):
    pass

def scan_directory(path):
    try:
        if not os.path.exists(path):
            raise FileNotFoundError(f"Invalid path: {path}")

        folder_counts = {}  # store folder -> file count

        for root, dirs, files in os.walk(path):
            print(root)
            for f in files:
                print("   ", f)
            folder_counts[root] = len(files)

            if not files and not dirs:
                raise MissingFileOrFolderError(f"Empty folder: {root}")

        # --- Plotting the graph ---
        if folder_counts:
            plt.bar(folder_counts.keys(), folder_counts.values())
            plt.xticks(rotation=45, ha="right")
            plt.title("Files per Folder")
            plt.xlabel("Folders")
            plt.ylabel("Number of Files")
            plt.tight_layout()
            plt.show()

    except Exception as e:
        print("Error:", e)


