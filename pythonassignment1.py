# ------------------ Q4: Sorting & Searching ------------------
def sorting_searching():
    student_ids = [105, 102, 110, 108, 101, 115]
    print("Original IDs:", student_ids)

    # Bubble Sort
    for i in range(len(student_ids)):
        for j in range(0, len(student_ids)-i-1):
            if student_ids[j] > student_ids[j+1]:
                student_ids[j], student_ids[j+1] = student_ids[j+1], student_ids[j]
    print("Sorted IDs (Bubble Sort):", student_ids)

    # Linear Search
    target = int(input("Enter ID to search: "))
    if target in student_ids:
        print("Linear Search: ID found at index", student_ids.index(target))
    else:
        print("Linear Search: ID not found")

    # Binary Search
    low, high = 0, len(student_ids)-1
    found = False
    while low <= high:
        mid = (low + high) // 2
        if student_ids[mid] == target:
            print("Binary Search: ID found at index", mid)
            found = True
            break
        elif student_ids[mid] < target:
            low = mid + 1
        else:
            high = mid - 1
    if not found:
        print("Binary Search: ID not found")

