# ------------------ Q1: Student Registration & Grade Evaluation ------------------
def student_registration():
    student_name = input("Enter student name: ")
    score = float(input("Enter exam score (0-100): "))

    if score >= 90 and score <= 100:
        grade, remark = "A", "Excellent"
    elif score >= 75:
        grade, remark = "B", "Very Good"
    elif score >= 60:
        grade, remark = "C", "Good"
    elif score >= 40:
        grade, remark = "D", "Average"
    else:
        grade, remark = "F", "Needs Improvement"

    print("\n--- Student Report ---")
    print("Name:", student_name)
    print("Score:", score)
    print("Grade:", grade)
    print("Performance Remark:", remark)

# ------------------ Q2: Course Enrollment ------------------
def course_enrollment():
    courses = []
    max_courses = 5
    print("=== Course Enrollment System ===")
    while True:
        if len(courses) >= max_courses:
            print("Maximum course limit reached!")
            break
        course_name = input("Enter course name (or 'done' to finish): ")
        if course_name.lower() == "done":
            break
        credits = input("Enter credit value: ")
        if not credits.isdigit() or int(credits) <= 0:
            print("Invalid credit value! Skipping entry...")
            continue
        courses.append((course_name, int(credits)))
        print(f"Course '{course_name}' added.\n")

    print("\n--- Enrollment Report ---")
    for course, credit in courses:
        print(f"Course: {course}, Credits: {credit}")
    print("Total courses enrolled:", len(courses))

